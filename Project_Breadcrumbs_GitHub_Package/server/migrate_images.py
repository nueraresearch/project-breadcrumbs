#!/usr/bin/env python3
"""Project Breadcrumbs — migrate frames written before encryption existed.

An ingest directory from before `imagecrypt.py` holds ordinary JPEGs in
`data/images/` and `images` rows whose `secure_object_ref` points at them. The
server now assumes every stored frame is ciphertext, so such a directory does
not decrypt: every read fails, and the frames are neither readable nor
protected.

This rewrites it into the current shape. For each row:

1. Read the file the row points at.
2. If it is already ciphertext, decrypt it and check it against the hash the
   row already holds. Nothing is rewritten.
3. If it is plaintext, check its SHA-256 against that same recorded hash, then
   encrypt it.
4. Write the ciphertext, read it back, and decrypt it again before trusting it.
5. Repoint the row, commit, and only then remove the plaintext.

**The hash check is the point.** `integrity_hash` was written when the frame
arrived, so it is the one piece of information in the directory that predates
this migration. Encrypting a file whose bytes no longer match it would seal a
swapped or corrupted frame and give it a verified-looking provenance. Those are
refused and left on disk for a person to look at.

**Re-running is safe.** A frame that is already encrypted is verified rather
than skipped, so a second run doubles as a check that the key still opens
everything.

**Stop the ingest server first.** This rewrites files and rows that a running
server would be reading, and a re-upload arriving mid-run could replace a
`(record_id, frame_index)` between the read and the update.

Usage:
    INGEST_DATA=data IMAGE_KEY=... python3 migrate_images.py --data-dir data --dry-run
    INGEST_DATA=data IMAGE_KEY=... python3 migrate_images.py --data-dir data
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sqlite3
import sys
import tempfile

import imagecrypt

JPEG_MAGIC = b"\xff\xd8\xff"


def _encrypted_name(ref: str) -> str:
    return ref if ref.endswith(".enc") else ref + ".enc"


def _resolve(image_dir: str, ref: str) -> str:
    """Joins a stored reference to the image directory, refusing escapes.

    References are generated by the server, but this reads a database on disk
    and writes files from it, so a corrupted or edited row must not be able to
    point outside the directory.
    """
    if (not ref or os.path.isabs(ref) or os.path.basename(ref) != ref
            or ref in (".", "..")):
        raise ValueError("reference would leave the image directory")
    return os.path.join(image_dir, ref)


def _atomic_write(path: str, blob: bytes) -> None:
    directory = os.path.dirname(path)
    fd, tmp = tempfile.mkstemp(dir=directory, suffix=".part")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(blob)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def _empty_report() -> dict:
    return {
        "migrated": 0,
        "verified": 0,
        "kept_plaintext": 0,
        "missing": [],
        "failed": [],
        "orphans": [],
    }


def migrate(data_dir: str, key: bytes, *, dry_run: bool = False,
            keep_plaintext: bool = False) -> dict:
    """Re-encrypts plaintext frames in place. Returns a report, never raises
    for a single bad frame."""
    data_dir = os.path.abspath(data_dir)
    image_dir = os.path.join(data_dir, "images")
    db_path = os.path.join(data_dir, "records.db")

    if not os.path.isdir(image_dir):
        raise FileNotFoundError(f"no image directory at {image_dir}")
    if not os.path.isfile(db_path):
        raise FileNotFoundError(f"no records.db at {db_path}")

    report = _empty_report()
    conn = sqlite3.connect(db_path, timeout=15)
    conn.row_factory = sqlite3.Row
    try:
        rows = conn.execute(
            "SELECT record_id, frame_index, secure_object_ref, integrity_hash"
            " FROM images ORDER BY record_id, frame_index").fetchall()

        for row in rows:
            record_id = row["record_id"]
            frame = row["frame_index"]
            label = f"{record_id}[{frame}]"
            ref = (row["secure_object_ref"] or "").strip()
            expected = row["integrity_hash"] or ""

            try:
                path = _resolve(image_dir, ref)
            except ValueError as exc:
                report["failed"].append((label, f"{ref!r}: {exc}"))
                continue

            if not os.path.isfile(path):
                report["missing"].append((label, ref))
                continue

            with open(path, "rb") as fh:
                blob = fh.read()

            # Already migrated: verify rather than trust the filename, so a
            # wrong key or a swapped file is caught on a re-run.
            if imagecrypt.is_encrypted(blob):
                try:
                    plain = imagecrypt.decrypt(key, blob)
                except imagecrypt.CryptoError as exc:
                    report["failed"].append((label, f"{ref}: {exc}"))
                    continue
                if (expected
                        and hashlib.sha256(plain).hexdigest() != expected):
                    report["failed"].append(
                        (label, f"{ref}: decrypts but does not match its "
                                f"recorded hash"))
                    continue
                report["verified"] += 1
                continue

            if not blob.startswith(JPEG_MAGIC):
                report["failed"].append(
                    (label, f"{ref}: neither ciphertext nor a JPEG"))
                continue

            digest = hashlib.sha256(blob).hexdigest()
            if expected and digest != expected:
                report["failed"].append(
                    (label, f"{ref}: SHA-256 does not match the recorded hash; "
                            f"refusing to encrypt a frame that may have been "
                            f"swapped"))
                continue

            if dry_run:
                report["migrated"] += 1
                continue

            enc_ref = _encrypted_name(ref)
            enc_path = _resolve(image_dir, enc_ref)
            sealed = imagecrypt.encrypt(key, blob)
            _atomic_write(enc_path, sealed)

            # Read the file back and decrypt it before the row is repointed:
            # a full disk or a bad key must surface here, not when a reviewer
            # asks for the frame.
            try:
                with open(enc_path, "rb") as fh:
                    round_trip = imagecrypt.decrypt(key, fh.read())
                if hashlib.sha256(round_trip).hexdigest() != digest:
                    raise imagecrypt.CryptoError(
                        "written frame does not decrypt to the original")
            except (OSError, imagecrypt.CryptoError) as exc:
                if os.path.exists(enc_path):
                    os.unlink(enc_path)
                report["failed"].append(
                    (label, f"{ref}: {exc}; plaintext left in place"))
                continue

            conn.execute(
                "UPDATE images SET secure_object_ref=?"
                " WHERE record_id=? AND frame_index=?",
                (enc_ref, record_id, frame))
            conn.commit()
            report["migrated"] += 1

            if keep_plaintext:
                report["kept_plaintext"] += 1
            elif os.path.abspath(enc_path) == os.path.abspath(path):
                # The row already pointed at the .enc name, so the file was
                # replaced in place; there is no separate plaintext to remove.
                pass
            else:
                try:
                    os.unlink(path)
                except OSError as exc:
                    report["failed"].append(
                        (label, f"{ref}: encrypted, but the plaintext copy "
                                f"could not be removed ({exc}); delete it by "
                                f"hand"))

        # Re-read rather than reusing `rows`: the loop repointed some of them,
        # and a stale set would report every freshly encrypted frame as an
        # orphan.
        referenced = {(r[0] or "") for r in conn.execute(
            "SELECT secure_object_ref FROM images")}
        for name in sorted(os.listdir(image_dir)):
            if name in referenced or not os.path.isfile(
                    os.path.join(image_dir, name)):
                continue
            if name.endswith(".part"):
                report["orphans"].append(
                    (name, "leftover temporary file; safe to delete"))
            elif name.endswith(".jpg"):
                report["orphans"].append(
                    (name, "plaintext file with no images row; left alone "
                           "because there is no hash to check it against"))
            elif name.endswith(".enc"):
                report["orphans"].append(
                    (name, "encrypted file with no images row; left alone"))
    finally:
        conn.close()

    return report


def _print(report: dict, data_dir: str, dry_run: bool) -> None:
    verb = "would migrate" if dry_run else "migrated"
    print(f"Frame migration — {os.path.abspath(data_dir)}")
    if dry_run:
        print("  dry run: nothing is written, renamed or deleted")
    print(f"  {verb:<19}{report['migrated']}")
    print(f"  {'already encrypted':<19}{report['verified']}"
          f"  (checked against their recorded hashes)")
    if report["kept_plaintext"]:
        print(f"  {'plaintext kept':<19}{report['kept_plaintext']}")
    print(f"  {'missing':<19}{len(report['missing'])}")
    print(f"  {'failed':<19}{len(report['failed'])}")

    def _list(title, items):
        if not items:
            return
        print(f"\n  {title}:")
        for first, second in items:
            print(f"    {first}  {second}")

    _list("missing", report["missing"])
    _list("failed", report["failed"])
    _list("not touched", report["orphans"])

    if report["kept_plaintext"]:
        print("\n  Plaintext copies were left in place. Remove them once the "
              "encrypted copies have been checked.")
    if report["migrated"] and not dry_run:
        print("\n  The rows now point at .jpg.enc files; reads, review and "
              "publication work as before.")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Encrypt frames stored before image encryption existed.")
    ap.add_argument("--data-dir",
                    default=os.environ.get("INGEST_DATA", "data"))
    ap.add_argument("--dry-run", action="store_true",
                    help="report what would happen, change nothing")
    ap.add_argument("--keep-plaintext", action="store_true",
                    help="leave the originals on disk after encrypting")
    args = ap.parse_args(argv)

    try:
        key = imagecrypt.key_from_env()
    except imagecrypt.CryptoError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    if key is None:
        print(f"error: {imagecrypt.KEY_ENV} is not set. Without the key there "
              f"is nothing to encrypt to, and no way to check frames that are "
              f"already encrypted.", file=sys.stderr)
        return 2

    try:
        report = migrate(args.data_dir, key, dry_run=args.dry_run,
                         keep_plaintext=args.keep_plaintext)
    except (OSError, sqlite3.Error) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    _print(report, args.data_dir, args.dry_run)

    if report["failed"] or report["missing"]:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
